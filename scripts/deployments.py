"""Record deployments and roll back to an earlier one.

Every successful `terraform apply` is recorded as a git tag (deploy/<timestamp>-<name>)
on the commit that holds the generated code (terraform/gen_*.tf) that was applied.
Undo = put back the generated code of an earlier deployment (or an empty one) and run
`terraform plan`: the plan lists exactly what will be removed or reverted in SCM, and
nothing changes until that plan is approved and applied. The PANW folder (folders.tf)
is never part of a rollback.

Usage:
  .venv\\Scripts\\python scripts\\deployments.py record <name>    after a successful apply
  .venv\\Scripts\\python scripts\\deployments.py list
  .venv\\Scripts\\python scripts\\deployments.py diff <tag>       generated code now vs. that deployment
  .venv\\Scripts\\python scripts\\deployments.py restore <tag>    roll back to that deployment
  .venv\\Scripts\\python scripts\\deployments.py restore empty    remove everything generated (keeps PANW)
"""
import re
import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TF = ROOT / "terraform"
PREFIX = "deploy/"
EMPTY = ("# GENERATED by scripts/deployments.py restore empty: no generated objects.\n\n"
         "locals {\n  panw_folder_snippets = []\n}\n")


def git(*args, check=True) -> str:
    res = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True)
    if check and res.returncode != 0:
        sys.exit(f"git {' '.join(args)} failed:\n{res.stderr.strip()}")
    return res.stdout.strip()


def gen_files_at(ref: str) -> list[str]:
    out = git("ls-tree", "--name-only", f"{ref}:terraform")
    return [f for f in out.splitlines() if re.fullmatch(r"gen_.*\.tf", f)]


def count_resources(text: str) -> int:
    return len(re.findall(r'^resource "', text, flags=re.M))


def cmd_record(name: str) -> None:
    if not re.fullmatch(r"[A-Za-z0-9._-]+", name):
        sys.exit("name: letters, digits, . _ - only")
    git("add", "terraform")
    if git("diff", "--cached", "--name-only"):
        git("commit", "-q", "-m", f"Deploy {name}\n\nRecorded by scripts/deployments.py after terraform apply.\n\n"
                                  "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>")
    tag = f"{PREFIX}{datetime.now():%Y%m%d-%H%M}-{name}"
    git("tag", "-a", tag, "-m", f"Applied to SCM: {name}")
    git("push", "-q", "origin", "HEAD", tag)
    print(f"Recorded {tag} at {git('rev-parse', '--short', 'HEAD')} and pushed it.")


def cmd_list() -> None:
    tags = git("tag", "--list", f"{PREFIX}*", "--sort=creatordate").splitlines()
    if not tags:
        print("No deployments recorded yet.")
        return
    for t in tags:
        n = sum(count_resources(git("show", f"{t}:terraform/{f}")) for f in gen_files_at(t))
        print(f"{t:45} {git('log', '-1', '--format=%h %ci', t):32} {n} generated resources")


def cmd_diff(tag: str) -> None:
    print(git("diff", "--stat", tag, "--", "terraform/") or "No difference in terraform/.")


def cmd_restore(target: str) -> None:
    for f in TF.glob("gen_*.tf"):
        f.unlink()
    if target == "empty":
        (TF / "gen_00_structure.tf").write_text(EMPTY, encoding="utf-8")
        n = 0
    else:
        if target not in git("tag", "--list", f"{PREFIX}*").splitlines():
            sys.exit(f"unknown deployment tag {target!r} - see: deployments.py list")
        n = 0
        for f in gen_files_at(target):
            text = git("show", f"{target}:terraform/{f}") + "\n"
            (TF / f).write_text(text, encoding="utf-8")
            n += count_resources(text)
    print(f"Generated code restored to {target} ({n} resources).")
    print("Nothing has changed in SCM. Next: terraform -chdir=terraform plan  - review every destroy / change,")
    print("then apply only after approval, and record it: deployments.py record rollback-<name>")


def main() -> int:
    args = sys.argv[1:]
    if not args or args[0] not in ("record", "list", "diff", "restore") or (args[0] != "list" and len(args) != 2):
        print(__doc__)
        return 2
    {"record": cmd_record, "list": cmd_list, "diff": cmd_diff, "restore": cmd_restore}[args[0]](*args[1:])
    return 0


if __name__ == "__main__":
    sys.exit(main())
